def persona_label(persona_id: str) -> str:
    """اسم الشخصية العربي الظاهر في الواجهة."""
    return PERSONAS.get(persona_id or "", {}).get("label", "")


def _persona_block(persona_id: str) -> str:
    """يبني كتلة الشخصية بالعربية لتُدرج في نص العميل (مخفية عن المتدرّب)."""
    p = PERSONAS.get(persona_id or "")
    if not p:
        return ""
    objections = random.sample(p["objections"], k=min(2, len(p["objections"])))
    lines = [
        "شخصيتك (أهم نقطة — تتصرف بها طوال المكالمة):",
        f"- طباعك: {p['personality']}",
        f"- أسلوب كلامك: {p['style']}",
        f"- حالتك النفسية: {p['emotion']}",
        f"- صبرك: {p['patience']}",
        f"- نية شرائك: {p['intent']}",
        f"- حساسيتك للسعر: {p['price']}",
        f"- معرفتك بالمنتج: {p['knowledge']}",
        f"- هدفك من المكالمة: {p['goals']}",
        f"- مخاوفك: {p['concerns']}",
        f"- طول ردودك: {p['length']}",
        f"- مدى تعاونك: {p['cooperation']}",
        f"- سلوكك مع المندوب: {p['escalation']}",
        f"- أشهر اعتراضاتك: {'، '.join(objections)}.",
    ]
    if p.get("rules"):
        lines.append(f"- قاعدة خاصة: {p['rules']}")
    return "\n".join(lines)


